"""
Clean the raw synthetic retail data and write Clean_*.csv plus a Cleaning Log.

Run:  python clean_dataset.py   (after generate_dataset.py)
"""
import os
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
RAW, OUT = os.path.join(HERE, "Raw Dataset"), os.path.join(HERE, "Cleaned Dataset")
os.makedirs(OUT, exist_ok=True)
log = []

p = pd.read_csv(os.path.join(RAW, "Products.csv"))
bad = p.Category != p.Category.str.title()
p["Category"] = p.Category.str.title()
p["DelistWeek"] = p.DelistWeek.astype("Int64")
log.append(("Products", "Category text set to title case", int(bad.sum())))
p.to_csv(os.path.join(OUT, "Clean_Products.csv"), index=False)

d = pd.read_csv(os.path.join(RAW, "Depots.csv"))
d.to_csv(os.path.join(OUT, "Clean_Depots.csv"), index=False)
log.append(("Depots", "No issues found", 0))

ph = pd.read_csv(os.path.join(RAW, "PriceHistory.csv"))
n0 = len(ph)
ph = ph[ph.TransactionStatus == "Active"].drop(columns="TransactionStatus")
log.append(("PriceHistory", "Inactive (cancelled / draft) price rows removed: only Active prices are used for pricing", n0 - len(ph)))
ph.to_csv(os.path.join(OUT, "Clean_PriceHistory.csv"), index=False)

f = pd.read_csv(os.path.join(RAW, "WeeklyStockSales.csv"))
n0 = len(f)
f = f.drop_duplicates()
log.append(("WeeklyStockSales", "Exact duplicate rows removed", n0 - len(f)))
bad = f.DepotID != f.DepotID.str.strip().str.upper()
f["DepotID"] = f.DepotID.str.strip().str.upper()
log.append(("WeeklyStockSales", "DepotID trimmed and upper-cased ('d3 ' -> 'D3')", int(bad.sum())))
n1 = len(f)
f = f.drop_duplicates(subset=["WeekStart", "DepotID", "SKU"])
log.append(("WeeklyStockSales", "Duplicates found after fixing DepotID removed", n1 - len(f)))
neg = f.ClosingStock < 0
f.loc[neg, "ClosingStock"] = 0
log.append(("WeeklyStockSales", "Negative ClosingStock (system error) set to 0", int(neg.sum())))
f["InStock"] = (f.ClosingStock > 0).astype(int)
f["LostUnits"] = (f.DemandUnits - f.UnitsSold).clip(lower=0)
log.append(("WeeklyStockSales", "Added InStock (closing stock > 0) and LostUnits (demand not met)", len(f)))
f = f.sort_values(["WeekStart", "DepotID", "SKU"])
f.to_csv(os.path.join(OUT, "Clean_WeeklyStockSales.csv"), index=False)

finals = {"Clean_Products": len(p), "Clean_Depots": len(d), "Clean_PriceHistory": len(ph), "Clean_WeeklyStockSales": len(f)}
with open(os.path.join(HERE, "Cleaning Log.md"), "w", encoding="utf-8") as fh:
    fh.write("# Data Cleaning Log\n\nGenerated by `clean_dataset.py`. Counts are rows (or values) affected.\n\n")
    fh.write("| Table | Issue / action | Count |\n|---|---|---:|\n")
    for t, a, n in log:
        fh.write(f"| {t} | {a} | {n:,} |\n")
    fh.write("\n## Final row counts\n\n| Table | Rows |\n|---|---:|\n")
    for k, v in finals.items():
        fh.write(f"| {k} | {v:,} |\n")
print(pd.DataFrame(log, columns=["Table", "Action", "Count"]).to_string(index=False))
